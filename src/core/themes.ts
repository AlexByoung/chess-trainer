export function themeName(key: string): string {
  return THEME_NAMES[key] ?? key;
}

/** Themes that are noise next to the tactical motif (length, source, evaluation). */
const HIDDEN = new Set(['short', 'long', 'veryLong', 'oneMove', 'master', 'masterVsMaster', 'superGM', 'crushing', 'advantage', 'equality']);

export function visibleThemes(themes: readonly string[]): string[] {
  const shown = themes.filter((t) => !HIDDEN.has(t));
  return shown.length ? shown : themes.slice(0, 2);
}

